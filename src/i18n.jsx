// Persian (fa) site-wide dictionary lives in its own module (it mirrors the
// en/ru/ar blocks above). Attaching it here makes `fa` a first-class locale
// across the whole site, not just the /invest page.
dict.fa = faDict

const I18nContext = createContext(null)

// RTL locales (Arabic + Persian). Both have full site-wide dictionaries and
// render in the Peyda font with dir="rtl" (see index.css).
const RTL = new Set(['ar', 'fa'])
const isValidLang = (code) => LANGS.some((l) => l.code === code)

// Phase 2: language is derived from the URL prefix (/ar, /ru, /fa; en = none),
// so each language is a distinct, crawlable URL. The first path segment is the
// source of truth; localStorage only remembers the last choice for the bare /.
function langFromPathname(pathname) {
  const m = (pathname || '/').match(/^\/(ar|ru|fa)(?=\/|$)/)
  return m ? m[1] : 'en'
}

// Captured ONCE at module load, BEFORE the provider's effect writes the current
// language into localStorage: was this browser ever here before?
const IS_FIRST_VISIT = (() => {
  try { return !localStorage.getItem(STORAGE_KEY) } catch { return false }
})()

// Geo → preferred language for first-time visitors landing on the bare EN URL.
// Country codes come from Vercel's x-vercel-ip-country via /api/geo.
const GEO_LANG = { RU: 'ru' }

export function I18nProvider({ children }) {
  const navigate = useNavigate()
  const { pathname } = useLocation()
  const lang = langFromPathname(pathname)

  // First visit + prefix-less (EN) URL → ask the server for the visitor's
  // country and switch to the matching localized URL. Runs once per session;
  // returning visitors and manual language choices are never overridden.
  useEffect(() => {
    if (typeof window === 'undefined' || !IS_FIRST_VISIT) return
    if (langFromPathname(window.location.pathname) !== 'en') return
    try {
      if (sessionStorage.getItem('ww_geo_done')) return
      sessionStorage.setItem('ww_geo_done', '1')
    } catch { return }
    fetch('/api/geo')
      .then((r) => (r.ok ? r.json() : null))
      .then((data) => {
        const target = data && GEO_LANG[data.country]
        if (!target) return
        const current = window.location.pathname
        if (langFromPathname(current) !== 'en') return
        const next = current === '/' ? `/${target}` : `/${target}${current}`
        navigate(next + window.location.search, { replace: true })
      })
      .catch(() => { /* geo unavailable → stay on EN */ })
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [])

  // Keep <html lang>/<dir> in sync with the URL-derived language.
  useEffect(() => {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = lang
      document.documentElement.dir = RTL.has(lang) ? 'rtl' : 'ltr'
    }
    if (typeof window !== 'undefined') {
      try { localStorage.setItem(STORAGE_KEY, lang) } catch { /* ignore */ }
    }
  }, [lang])

  // Switching language navigates to the same logical page under the new prefix.
  const setLang = (code) => {
    if (!isValidLang(code)) return
    const logical = pathname.replace(/^\/(ar|ru|fa)(?=\/|$)/, '') || '/'
    const next = code === 'en' ? logical : (logical === '/' ? `/${code}` : `/${code}${logical}`)
    navigate(next)
  }

  return (
    <I18nContext.Provider value={{ lang, setLang, t: dict[lang] || dict.en }}>
      {children}
    </I18nContext.Provider>
  )
}

export function useI18n() {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider')
  return ctx
}
